import React from 'react';

/**
 * PrintHeader renders the top of the printed document (visible only during print).
 */
export const PrintHeader = ({ title }) => {
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  const timeStr = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false });

  return (
    <div className="print-only print-header-container">
      <img src="/logo/hotel-logo.png" alt="Company Logo" className="print-logo" />
      <h1 className="print-company-name">ALFA HOTEL MANAGEMENT SYSTEM</h1>
      <h2 className="print-report-title">{title}</h2>
      <div className="print-date-time">
        Date: {dateStr} &nbsp;|&nbsp; Time: {timeStr}
      </div>
    </div>
  );
};

/**
 * PrintFooter renders the bottom of the printed document (visible only during print).
 */
export const PrintFooter = ({ title }) => {
  const now = new Date();
  const dateStr = now.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' });
  const timeStr = now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: false });

  return (
    <div className="print-only print-footer-container">
      <div className="flex justify-between w-full text-slate-500 font-medium px-4">
        <span>Generated by ALFA Hotel Management System</span>
        <span>Report: {title}</span>
        <span>Date: {dateStr} | Time: {timeStr}</span>
      </div>
    </div>
  );
};
